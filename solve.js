// run(input) returns exactly makefun-site 1.0.0's build(input) for every input: the output
// tree (path -> text) of the site, byte for byte. Written from the reference's behaviour
// (its README and code); no vendor code is copied into this repository.
// Optimisations over the reference: fast paths for plain text (no Markdown or HTML
// specials), ASCII-only slugs, a per-case slug cache, manual line classification instead
